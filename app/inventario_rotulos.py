def _de_reserva(nome: str) -> str:
    texto = nome.replace("_", " ").strip().lower()
    return texto[:1].upper() + texto[1:]


def rotulo_da_tabela_do_inventario(tabela: str) -> str:
    return _TABELAS_A_MAIS.get(tabela) or ROTULO_DA_TABELA.get(tabela) or _de_reserva(tabela)


def rotulo_da_coluna(coluna: str) -> str:
    return ROTULO_DA_COLUNA.get(coluna) or _de_reserva(coluna)


def rotulo_do_dado(dado: str) -> str:
    """"pessoas.cpf" vira "CPF (Pessoas)"; um nome sem ponto é uma tabela."""
    if "." not in dado:
        return rotulo_da_tabela_do_inventario(dado)
    tabela, coluna = dado.split(".", 1)
    return f"{rotulo_da_coluna(coluna)} ({rotulo_da_tabela_do_inventario(tabela)})"
