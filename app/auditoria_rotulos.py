def _de_reserva(nome: str) -> str:
    texto = nome.replace("_", " ").strip().lower()
    return texto[:1].upper() + texto[1:]


def rotulo_da_tabela(tabela: str | None) -> str | None:
    if tabela is None:
        return None
    return ROTULO_DA_TABELA.get(tabela) or _de_reserva(tabela)


def rotulo_da_acao(acao: str | None) -> str | None:
    if acao is None:
        return None
    return ROTULO_DA_ACAO.get(acao) or _de_reserva(acao)
